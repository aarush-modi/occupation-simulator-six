// Validate every prop recipe and write src/shared/catalog/catalog.generated.js.
// Usage: node scripts/catalog.mjs            (validate + build)
//        node scripts/catalog.mjs --check a b (validate only the given ids)
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { Recipe, LIMITS } from '../src/shared/schema.js';

const here = path.dirname(fileURLToPath(import.meta.url));
const dir = path.join(here, '../src/shared/catalog/props');
const out = path.join(here, '../src/shared/catalog/catalog.generated.js');
const only = process.argv.includes('--check') ? process.argv.slice(process.argv.indexOf('--check') + 1) : null;

const errors = [];
const recipes = [];
const seen = new Set();
for (const f of fs.readdirSync(dir).filter((f) => f.endsWith('.json')).sort()) {
  const id = f.replace(/\.json$/, '');
  if (only && !only.includes(id)) continue;
  let raw;
  try { raw = JSON.parse(fs.readFileSync(path.join(dir, f), 'utf8')); } catch (e) { errors.push(`${f}: invalid JSON: ${e.message}`); continue; }
  const r = Recipe.safeParse(raw);
  if (!r.success) { errors.push(`${f}: ${r.error.issues.slice(0, 4).map((i) => `${i.path.join('.')}: ${i.message}`).join('; ')}`); continue; }
  const rec = r.data;
  if (rec.id !== id) errors.push(`${f}: id "${rec.id}" must match filename`);
  if (seen.has(rec.id)) errors.push(`${f}: duplicate id`);
  seen.add(rec.id);
  const lim = LIMITS[rec.kind];
  const [w, h, d] = rec.size;
  if (w > lim.w + 1e-6 || h > lim.h + 1e-6 || d > lim.d + 1e-6) errors.push(`${f}: size ${rec.size} exceeds ${rec.kind} limit ${lim.w}x${lim.h}x${lim.d}`);
  const inside = ([x, y, z]) => Math.abs(x) <= w / 2 + 0.3 && y >= -0.05 && y <= h + 0.3 && Math.abs(z) <= d / 2 + 0.3;
  for (const s of rec.slots) if (!inside(s.pos)) errors.push(`${f}: slot ${s.id} outside bounding box`);
  for (const c of rec.controls) {
    if (!inside(c.pos)) errors.push(`${f}: control ${c.id} outside bounding box`);
    for (const req of c.requires) if (!rec.slots.find((s) => s.id === req)) errors.push(`${f}: control ${c.id} requires unknown slot ${req}`);
  }
  recipes.push(rec);
}

if (errors.length) {
  console.error(`${errors.length} problem(s):\n` + errors.map((e) => ' - ' + e).join('\n'));
  process.exitCode = 1;
}
if (!only) {
  fs.writeFileSync(out, '// Generated by scripts/catalog.mjs. Do not edit.\nexport const CATALOG = ' + JSON.stringify(recipes) + ';\n');
  const byShell = {};
  for (const r of recipes) for (const s of r.shells) byShell[s] = (byShell[s] ?? 0) + 1;
  console.log(`catalog: ${recipes.length} valid recipes`, byShell);
} else if (!errors.length) console.log(`ok: ${recipes.length} recipe(s) valid`);
